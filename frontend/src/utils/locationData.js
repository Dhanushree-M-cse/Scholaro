/**
 * Helper to get districts for a state, falling back to a default list or custom input
 */
export const getDistrictsForState = (stateName) => {
  if (!stateName) return [];
  if (DISTRICTS_BY_STATE[stateName]) {
    return DISTRICTS_BY_STATE[stateName];
  }
  // Default list of general districts for states without explicit mapping
  return [
    'Central District',
    'East District',
    'North District',
    'South District',
    'West District',
    'Capital District',
    'Other District'
  ];
};
